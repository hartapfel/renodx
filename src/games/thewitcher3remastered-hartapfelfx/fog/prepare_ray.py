import argparse
import hashlib
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[4]
source = Path(__file__).with_name("0xF7F00009.lib_6_6.hlsl")
header = source.with_name("ray_local.generated.hpp")

def dependencies(path, seen):
    path = path.resolve()
    if path in seen:
        return
    seen.add(path)
    for name in re.findall(r'^\s*#include\s+"([^"]+)"', path.read_text(), re.M):
        dependencies(path.parent / name, seen)

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
files = set()
dependencies(source, files)
digest = hashlib.sha256()
for path in sorted(files):
    digest.update(path.relative_to(root).as_posix().encode())
    # Git may check text out with CRLF on Windows; line endings do not change
    # shader semantics and must not make a clean checkout appear stale.
    digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
stamp = "// Source SHA256 " + digest.hexdigest()
if args.check:
    if not header.exists() or stamp not in header.read_text():
        raise SystemExit("Fog ray bytecode is stale: run fog/prepare_ray.py")
else:
    directory = root / "tmp/hartapfelfx-validation"
    directory.mkdir(parents=True, exist_ok=True)
    binary = directory / "fog-ray-local.cso"
    subprocess.run([str(root / "bin/dxc.exe"), "-T", "lib_6_6", "-HV", "2021", "-Ges", "-WX",
                    "-Fo", str(binary), str(source)], check=True)
    data = binary.read_bytes()
    rows = ["  " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 24]) + ","
            for offset in range(0, len(data), 24)]
    header.write_text("// Generated by fog/prepare_ray.py. SPDX-License-Identifier: MIT\n" + stamp +
                      "\n#pragma once\n#include <cstdint>\nnamespace hartapfelfx::fog::rays {\n"
                      "inline constexpr uint8_t local_code[] = {\n" + "\n".join(rows) + "\n};\n}\n")
print("PASS fog ray source/bytecode identity")
