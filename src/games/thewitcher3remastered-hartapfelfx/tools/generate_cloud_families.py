"""Generate static cloud recipes from a read-only installed weather-table audit.

python tools/generate_cloud_families.py <installed-cloud-weather.json>
The audit is development evidence; the game addon never reads bundles or JSON.
"""
import argparse
import json
from pathlib import Path

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument("audit",type=Path)
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
recipes=json.loads((root/"clouds/family_effects.json").read_text())
audit=json.loads(args.audit.read_text())
regions={"weather_novigrad.csv":1,"weather_skellige.csv":2,"weather_kaer_morhen.csv":3,
         "weather_prolog.csv":4,"weather_winter_epilog.csv":8,"weather_bob.csv":11}
rows={}
for table in sorted(audit["tables"],key=lambda t:t["bundle"].lower().startswith("mods")):
    region=regions.get(table["resource"].split("\\")[-1])
    if region is None:continue
    for row in table["rows"]:
        name=(row.get("name") or "").strip("\x00 ")
        if not name:continue
        weights=[0.]*5
        matched=False
        for key,path in row.items():
            if not key.endswith("_effect") or not path:continue
            recipe=recipes.get(path.split("\\")[-1])
            if recipe is None:continue
            prefix=key[:-6]
            strength=float(row.get(prefix+"strength") or 1)
            probability=float(row.get(prefix+"prob") or 1)
            if probability<=0:continue
            matched=True
            # Expected presence of optional effects, not a new random emitter
            # simulation. Native fade and native wind are independent inputs.
            for i,value in enumerate(recipe):
                weights[i]=max(weights[i],value*min(strength,1)*probability)
        if not matched:continue
        cover=.65 if row.get("fakeShadow")=="0" and max(weights[:2])>0 else 0.
        # Light-cloud weather can be authored entirely with the removed flat
        # alto/cirrus sheets. Retain a light volumetric formation in that case;
        # otherwise the family fade erases the entire sky after a weather change.
        # Native coverage still supplies the gaps, with no new coverage floor.
        if name=="WT_Light_Clouds" and max(weights[:2])==0:
            weights[0]=.45
        clear=float(name=="WT_Clear")
        light=float(name=="WT_Light_Clouds")
        # Weather texture slots are not precipitation identities. Use the
        # audited native weather/effect record, including regional quest rain.
        effects=[path.lower() for key,path in row.items() if key.endswith("_effect") and path
            and float(row.get(key[:-6]+"prob") or 1)>0
            and float(row.get(key[:-6]+"strength") or 1)>0]
        severe=float(row.get("backgroundThunder","").lower()=="true"
            or any(word in name.lower() for word in ("rain","drizzle","storm","blizzard","thunder"))
            or any(any(word in path for word in ("rain","drizzle","storm","blizzard","thunder")) for path in effects))
        # Formation fill, independent of cloud type. Named photo-mode states
        # keep their order even with Coverage at 200%.
        if name=="WT_Clear":
            fill=0.
            weights[:2]=[0.,0.]
            cover=0.
        elif name=="WT_Light_Clouds":
            fill=.13
        elif name.startswith("WT_Mid_Clouds"):
            fill=.35
        elif name.startswith("WT_Heavy_") or name in ("WT_Light_Rain","WT_Snow"):
            fill=.60
        else:
            # Storms and other quest weather keep the full native fill.
            fill=1.
        rows[(region,name)]={"low":weights[:2]+[clear,light],"high":[fill,1.,cover,severe]}
profiles=[{"low":[1,0,0,0],"high":[1,0,0,0]}]
names=sorted({name for _,name in rows})
entries=[]
for (region,name),profile in sorted(rows.items()):
    if profile not in profiles:profiles.append(profile)
    entries.append((region,names.index(name),profiles.index(profile),name))
assert len(profiles)<256

def vector(values):
    return "{"+",".join(f"{value:.6f}f" for value in values)+"}"

lines=["""// Copyright (C) 2026 Hartapfel. SPDX-License-Identifier: MIT
// Generated by tools/generate_cloud_families.py; edit family_effects.json.
#pragma once
#include <array>
#include <atomic>
#include <bit>
#include <cstdint>
namespace hartapfelfx::clouds::families {
struct Profile { std::array<float,4> low, high; };
// low: cumulus, stratus deck, clear weather, light-cloud weather; high: formation fill, known, fallback cover, severe weather.
inline constexpr Profile profiles[] = {
"""]
for profile in profiles:
    lines.append("    {"+vector(profile["low"])+","+vector(profile["high"])+"},\n")
lines.append("};\nstruct Name { const char* text; uint32_t native = 0; };\ninline Name names[] = {\n")
for name in names:lines.append('    {"'+name+'"},\n')
lines.append("};\nstruct Weather { uint32_t region, name, profile; };\ninline constexpr Weather weather[] = {\n")
for region,name,profile,label in entries:
    lines.append(f"    {{{region},{name},{profile}}}, // {label}\n")
lines.append("""};
// Source/target recipe IDs and exact native float blend in one lock-free word.
// Zero selects the previous generic field; renderer workers never read game RAM.
inline std::atomic<uint64_t> current = 0;
static_assert(std::atomic<uint64_t>::is_always_lock_free);
inline uint32_t Find(uint32_t region, uint32_t name) {
  if(name==0)return 0;
  for(const auto& row:weather)
    if(row.region==region && names[row.name].native==name)return row.profile;
  return 0;
}
} // namespace hartapfelfx::clouds::families
""")
output=root/"clouds/families.hpp"
generated="".join(lines)
if not output.exists() or output.read_text()!=generated:
    output.write_text(generated)
print(f"Generated {len(profiles)} profiles, {len(entries)} regional weather rows, {len(names)} names")
